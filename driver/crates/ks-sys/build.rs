//! Generates the raw kernel streaming bindings.
//!
//! Two outputs, both written to `OUT_DIR`:
//!
//! * `ks.rs`: bindgen output for a tight allowlist of types, functions and
//!   integer constants from `ks.h` and `ksmedia.h`. Types that the base WDK
//!   headers define (IRP, DEVICE_OBJECT, GUID, ...) are not generated again;
//!   the generated code takes them from Microsoft's `wdk-sys`.
//! * `guids.rs`: the GUID constants. `ks.h` declares each GUID with
//!   `DEFINE_GUIDSTRUCT("<guid>", NAME)`, which in C becomes a
//!   `__declspec(selectany)` variable. bindgen can only turn that into an
//!   `extern` declaration, which nothing would define at link time, so the
//!   `DEFINE_GUIDSTRUCT` lines are read from the headers directly and emitted
//!   as Rust constants.

