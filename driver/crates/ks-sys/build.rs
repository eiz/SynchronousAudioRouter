fn main() -> Result<(), Box<dyn std::error::Error>> {
    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let config = Config::from_env_auto()?;

    generate_bindings(&config, &out_dir)?;
    generate_guids(&config, &out_dir)?;

    // ks.lib is the import library of ks.sys.
    for path in config.library_paths()? {
        println!("cargo::rustc-link-search={}", path.display());
    }
    println!("cargo::rustc-link-lib=static=ks");
    Ok(())
}

fn generate_bindings(config: &Config, out_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let header = "\
#include <ntifs.h>
#include <ntddk.h>
#include <windef.h>
#include <ks.h>
#include <ksmedia.h>
";
    let mut builder = bindgen::Builder::wdk_default(config)?
        .with_codegen_config(
            CodegenConfig::TYPES | CodegenConfig::FUNCTIONS | CodegenConfig::VARS,
        )
        .header_contents("ks-input.h", header)
        // Base WDK types come from wdk-sys.
        .allowlist_recursively(false)
        // With the base types left to wdk-sys, bindgen cannot see that they
        // are `Copy`; without this it would replace every union that
        // contains one (KSIDENTIFIER, KSDATAFORMAT, ...) by an opaque blob.
        .default_non_copy_union_style(bindgen::NonCopyUnionStyle::ManuallyDrop)
        // No generated `Default` impls: bindgen writes them as unsafe
        // zero-fills, and nothing here needs them.
        .derive_default(false)
        .layout_tests(false);
    for name in TYPES {
        builder = builder.allowlist_type(format!("^{name}$"));
    }
    for name in OPAQUE_TYPES {
        builder = builder.opaque_type(format!("^{name}$"));
    }
    for name in FUNCTIONS {
        builder = builder.allowlist_function(format!("^{name}$"));
    }
    for name in VARS {
        builder = builder.allowlist_var(format!("^{name}$"));
    }
    builder
        .generate()?
        .write_to_file(out_dir.join("ks.rs"))?;
    Ok(())
}

/// Collects every `DEFINE_GUIDSTRUCT("xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx", NAME);`
/// in a header as NAME -> GUID string.
fn guidstruct_definitions(text: &str) -> HashMap<String, String> {
    let mut map = HashMap::new();
    for line in text.lines() {
        let Some(rest) = line.trim_start().strip_prefix("DEFINE_GUIDSTRUCT(") else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix('"') else {
            continue;
        };
        let Some((guid, rest)) = rest.split_once('"') else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix(',') else {
            continue;
        };
        let name: String = rest
            .trim_start()
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect();
        if !name.is_empty() {
            map.insert(name, guid.to_string());
        }
    }
    map
}

/// Parses `xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx` into Data1, Data2, Data3 and
/// the eight bytes of Data4.
fn parse_guid(text: &str) -> Option<(u32, u16, u16, [u8; 8])> {
    let parts: Vec<&str> = text.split('-').collect();
    if parts.len() != 5
        || parts[0].len() != 8
        || parts[1].len() != 4
        || parts[2].len() != 4
        || parts[3].len() != 4
        || parts[4].len() != 12
    {
        return None;
    }
    let data1 = u32::from_str_radix(parts[0], 16).ok()?;
    let data2 = u16::from_str_radix(parts[1], 16).ok()?;
    let data3 = u16::from_str_radix(parts[2], 16).ok()?;
    let tail = format!("{}{}", parts[3], parts[4]);
    let mut data4 = [0u8; 8];
    for (i, byte) in data4.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&tail[i * 2..i * 2 + 2], 16).ok()?;
    }
    Some((data1, data2, data3, data4))
}

fn generate_guids(config: &Config, out_dir: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let mut definitions = HashMap::new();
    for header in ["ks.h", "ksmedia.h"] {
        let path = config
            .include_paths()?
            .map(|dir| dir.join(header))
            .find(|p| p.exists())
            .ok_or_else(|| format!("{header} not found in the WDK include paths"))?;
        println!("cargo::rerun-if-changed={}", path.display());
        // The headers are not guaranteed to be valid UTF-8.
        let text = String::from_utf8_lossy(&fs::read(&path)?).into_owned();
        definitions.extend(guidstruct_definitions(&text));
    }

    let mut out = String::from(
        "// Generated by build.rs from the DEFINE_GUIDSTRUCT lines of ks.h and ksmedia.h.\n\n",
    );
    for name in GUIDS {
        let text = definitions
            .get(*name)
            .ok_or_else(|| format!("no DEFINE_GUIDSTRUCT for {name} in ks.h or ksmedia.h"))?;
        let (d1, d2, d3, d4) =
            parse_guid(text).ok_or_else(|| format!("malformed GUID string for {name}: {text}"))?;
        out.push_str(&format!(
            "/// `{{{text}}}`\npub const {name}: GUID = GUID {{ Data1: {d1:#010x}, Data2: {d2:#06x}, Data3: {d3:#06x}, Data4: [{}] }};\n",
            d4.iter()
                .map(|b| format!("{b:#04x}"))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    fs::write(out_dir.join("guids.rs"), out)?;
    Ok(())
}
